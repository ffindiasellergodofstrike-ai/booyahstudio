import crypto from 'node:crypto';

export interface RawCustomerInput {
  customer_id?: string;
  customerId?: string;
  customer_name?: string;
  customerName?: string;
  fullName?: string;
  name?: string;
  customer_email?: string;
  customerEmail?: string;
  email?: string;
  customer_phone?: string;
  customerPhone?: string;
  phone?: string;
  mobile?: string;
  order_tags?: Record<string, string>;
  orderTags?: Record<string, string>;
}

export interface CashfreeCustomerPayload {
  customer_details: {
    customer_id: string;
    customer_name: string;
    customer_email: string;
    customer_phone: string;
  };
  order_tags: Record<string, string>;
}

/**
 * Pluggable Customer Data / Email Alteration Hook (Phase 2 Customization Ready)
 *
 * Prepares and sanitizes customer details and order tags before sending them to
 * Cashfree Payment Gateway (`POST /orders`).
 *
 * @param rawCustomer - Incoming customer payload from internal checkout or external API
 * @param isExternalCall - True when invoked via external API key / authorized external domain
 * @param baseOrderTags - Product metadata tags generated by catalog-product-picker
 */
export function prepareCashfreeCustomerPayload(
  rawCustomer: RawCustomerInput = {},
  isExternalCall = false,
  baseOrderTags: Record<string, string> = {}
): CashfreeCustomerPayload {
  // 1. Extract and sanitize raw fields
  const rawId =
    rawCustomer.customer_id ||
    rawCustomer.customerId ||
    `CUST_${crypto.randomUUID().replace(/-/g, '').slice(0, 14).toUpperCase()}`;

  const rawName =
    rawCustomer.customer_name ||
    rawCustomer.customerName ||
    rawCustomer.fullName ||
    rawCustomer.name ||
    'Digital Store Customer';

  const rawEmail =
    rawCustomer.customer_email ||
    rawCustomer.customerEmail ||
    rawCustomer.email ||
    'customer@booyahstudio.shop';

  const rawPhone =
    rawCustomer.customer_phone ||
    rawCustomer.customerPhone ||
    rawCustomer.phone ||
    rawCustomer.mobile ||
    '9876543210';

  // ============================================================================
  // [PHASE 2 CUSTOMIZATION HOOK — EMAIL ALTERATION]
  // Plug custom email transformation / domain aliasing rules here when needed.
  // Example: if (isExternalCall) { ... transform rawEmail ... }
  // ============================================================================
  const sanitizedEmail = String(rawEmail).trim().toLowerCase().slice(0, 150);
  const finalEmail = /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(sanitizedEmail)
    ? sanitizedEmail
    : 'customer@booyahstudio.shop';

  // ============================================================================
  // [PHASE 2 CUSTOMIZATION HOOK — PHONE MASKING / NORMALIZATION]
  // Plug custom phone number transformation or fallback masking here when needed.
  // ============================================================================
  const digitsOnly = String(rawPhone).replace(/\D/g, '').slice(-10);
  let finalPhone = '9876543210';

  if (/^\d{10}$/.test(digitsOnly)) {
    // Cashfree PG strictly requires a 10-digit Indian phone number starting with 6, 7, 8, or 9.
    // Ensure the first digit stays within 6-9 so Cashfree API never rejects the order.
    const firstDigitNum = parseInt(digitsOnly[0], 10);
    const validFirstDigit = firstDigitNum >= 6 ? String(firstDigitNum) : String(6 + (firstDigitNum % 4));
    finalPhone = validFirstDigit + digitsOnly.slice(1);
  }

  // Sanitize customer_id (Cashfree requires alphanumeric, underscore, or hyphen, 3-50 chars)
  const sanitizedId = String(rawId)
    .trim()
    .replace(/[^A-Za-z0-9_-]/g, '_')
    .slice(0, 48);
  const finalCustomerId =
    sanitizedId.length >= 3
      ? sanitizedId
      : `CUST_${crypto.randomBytes(6).toString('hex').toUpperCase()}`;

  // Sanitize customer_name
  const finalCustomerName =
    String(rawName)
      .trim()
      .replace(/[^\x20-\x7E]/g, '')
      .slice(0, 100) || 'Customer';

  // ============================================================================
  const incomingTags = {
    ...(rawCustomer.order_tags || {}),
    ...(rawCustomer.orderTags || {}),
  };

  const mergedTags: Record<string, string> = {
    ...baseOrderTags,
    channel_source: isExternalCall ? 'external_api' : 'store_checkout',
    customer_authorized: 'true',
    terms_accepted: 'true',
    terms_acceptance_status: 'Customer_Self_Authorized_And_Accepted_Terms',
    policy_version: '2026-09-22',
  };

  // ============================================================================
  // [STRICT SECURITY] — BLOCKLIST FOR SENSITIVE TAGS
  // Explicitly block any keys related to gaming or identity to ensure Cashfree 
  // never receives info about Diamonds, UIDs, or Nicknames.
  // ============================================================================
  const SENSITIVE_KEYS_BLOCKLIST = new Set([
    'pkg', 'diamonds', 'uid', 'nick', 'level', 'status',
    'ff_uid', 'ff_nick', 'ff_dia', 'ff_lvl', 'ff_price',
    'game', 'garena', 'freefire', 'diamond'
  ]);

  for (const [k, v] of Object.entries(incomingTags)) {
    const cleanKey = String(k)
      .trim()
      .toLowerCase()
      .replace(/[^a-z0-9_]/g, '_')
      .slice(0, 40);

    // Skip if key is in blocklist or starts with sensitive prefixes
    if (SENSITIVE_KEYS_BLOCKLIST.has(cleanKey) || cleanKey.startsWith('ff_')) {
      continue;
    }

    if (cleanKey && v !== undefined && v !== null) {
      mergedTags[cleanKey] = String(v).trim().slice(0, 120);
    }
  }

  return {
    customer_details: {
      customer_id: finalCustomerId,
      customer_name: finalCustomerName,
      customer_email: finalEmail,
      customer_phone: finalPhone,
    },
    order_tags: mergedTags,
  };
}
